#!/usr/bin/env python3
"""Emit files as C byte arrays.

    embed_file.py <output.inc> <name=file> ...

Used for the window icon, so the shell has no runtime file dependency on the
source tree.
"""

import os
import sys


def main(argv):
    if len(argv) < 3:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    destination = argv[1]
    parts = []
    for entry in argv[2:]:
        name, _, path = entry.partition("=")
        with open(path, "rb") as source:
            data = source.read()
        body = ",\n    ".join(", ".join(f"0x{byte:02x}" for byte in data[i:i + 16]) for i in range(0, len(data), 16))
        parts.append(f"// {os.path.basename(path)}, {len(data)} bytes\n"
                     f"constexpr std::uint8_t {name}[] = {{\n    {body},\n}};\n")
    os.makedirs(os.path.dirname(destination), exist_ok=True)
    with open(destination, "w") as out:
        out.write("// Generated by tools/embed_file.py. Do not edit.\n\n")
        out.write("\n".join(parts))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
